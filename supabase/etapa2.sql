create extension if not exists pgcrypto;

create table if not exists public.countries (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  flag text,
  is_active boolean not null default true,
  president_available boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.profiles
  add column if not exists player_number bigint generated by default as identity,
  add column if not exists role text not null default 'citizen',
  add column if not exists country_id uuid references public.countries(id),
  add column if not exists registration_status text not null default 'active';

create unique index if not exists profiles_player_number_uidx
  on public.profiles(player_number);
create unique index if not exists profiles_one_president_per_country_uidx
  on public.profiles(country_id) where role = 'president' and country_id is not null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'profiles_role_check') then
    alter table public.profiles add constraint profiles_role_check
      check (role in ('citizen','president','super_admin'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'profiles_registration_status_check') then
    alter table public.profiles add constraint profiles_registration_status_check
      check (registration_status in ('active','pending_presidency','rejected'));
  end if;
end $$;

create table if not exists public.president_applications (
  id uuid primary key default gen_random_uuid(),
  player_id uuid not null references public.profiles(id) on delete cascade,
  country_id uuid not null references public.countries(id),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  requested_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references public.profiles(id),
  review_note text
);

create unique index if not exists president_applications_one_pending_per_player_uidx
  on public.president_applications(player_id) where status = 'pending';
create unique index if not exists president_applications_one_pending_per_country_uidx
  on public.president_applications(country_id) where status = 'pending';

alter table public.countries enable row level security;
alter table public.president_applications enable row level security;

-- Remove privilégios diretos que poderiam permitir escalada de função.
-- O trigger cria perfis; o cliente só pode editar nickname e foto.
revoke insert, update, delete on public.profiles from public, anon, authenticated;
grant select on public.profiles to anon, authenticated;
grant update (username, avatar_url) on public.profiles to authenticated;
drop policy if exists "Inserir o próprio perfil" on public.profiles;

-- Solicitações e países são alterados exclusivamente pelas funções administrativas/registro.
revoke insert, update, delete on public.president_applications from public, anon, authenticated;
revoke insert, update, delete on public.countries from public, anon, authenticated;

-- Perfis públicos para exibir identidade, mas campos de privilégio não podem ser alterados pelo cliente.

drop policy if exists "Solicitações visíveis ao dono e admin" on public.president_applications;
create policy "Solicitações visíveis ao dono e admin" on public.president_applications
  for select to authenticated
  using (player_id = auth.uid() or public.is_world_admin());

create or replace function public.is_world_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'super_admin'
  );
$$;

-- Recria a policy de países após criar a função de autorização.
drop policy if exists "Países ativos visíveis" on public.countries;
create policy "Países ativos visíveis" on public.countries
  for select to anon, authenticated using (is_active or public.is_world_admin());

grant select on public.countries to anon, authenticated;
grant select on public.president_applications to authenticated;

create or replace function public.register_player(p_type text, p_country_id uuid)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_country public.countries%rowtype;
  v_profile public.profiles%rowtype;
  v_application_id uuid;
begin
  if v_uid is null then raise exception 'É necessário entrar na conta.'; end if;
  if p_type not in ('citizen','president') then raise exception 'Tipo de jogador inválido.'; end if;
  select * into v_profile from public.profiles where id = v_uid for update;
  if not found then raise exception 'Perfil do jogador não encontrado.'; end if;
  if v_profile.role = 'super_admin' then
    return jsonb_build_object('status','active','role','super_admin');
  end if;
  if v_profile.country_id is not null or v_profile.registration_status <> 'active' then
    raise exception 'Esta conta já possui uma escolha de país ou solicitação registrada.';
  end if;
  select * into v_country from public.countries
    where id = p_country_id and is_active = true for update;
  if not found then raise exception 'País indisponível. Atualize a lista e tente novamente.'; end if;

  if p_type = 'citizen' then
    update public.profiles
      set country_id = v_country.id, role = 'citizen', registration_status = 'active'
      where id = v_uid;
    return jsonb_build_object('status','active','role','citizen','country_id',v_country.id);
  end if;

  if not v_country.president_available then
    raise exception 'Este país não está aceitando solicitações de presidência.';
  end if;
  if exists (select 1 from public.profiles where country_id = v_country.id and role = 'president') then
    raise exception 'Este país já possui um presidente.';
  end if;
  insert into public.president_applications(player_id,country_id)
    values (v_uid,v_country.id) returning id into v_application_id;
  update public.profiles set registration_status = 'pending_presidency' where id = v_uid;
  return jsonb_build_object('status','pending','application_id',v_application_id,'country_id',v_country.id);
end;
$$;

create or replace function public.review_president_application(p_application_id uuid, p_decision text, p_note text default null)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_app public.president_applications%rowtype;
  v_country public.countries%rowtype;
begin
  if not public.is_world_admin() then raise exception 'Apenas o Super Admin pode revisar solicitações.'; end if;
  if p_decision not in ('approved','rejected') then raise exception 'Decisão inválida.'; end if;
  select * into v_app from public.president_applications
    where id = p_application_id and status = 'pending' for update;
  if not found then raise exception 'Solicitação não encontrada ou já revisada.'; end if;
  select * into v_country from public.countries where id = v_app.country_id for update;
  if p_decision = 'approved' then
    if not v_country.is_active or not v_country.president_available then
      raise exception 'O país não está mais disponível para presidência.';
    end if;
    if exists (select 1 from public.profiles where country_id = v_country.id and role = 'president') then
      raise exception 'Este país já possui um presidente.';
    end if;
    update public.profiles set role='president', country_id=v_country.id, registration_status='active'
      where id=v_app.player_id;
    update public.countries set president_available=false where id=v_country.id;
  else
    update public.profiles set registration_status='rejected' where id=v_app.player_id;
  end if;
  update public.president_applications
    set status=p_decision, reviewed_at=now(), reviewed_by=auth.uid(), review_note=nullif(trim(p_note),'')
    where id=v_app.id;
  return jsonb_build_object('status',p_decision,'application_id',v_app.id,'country_id',v_app.country_id);
end;
$$;

create or replace function public.admin_save_country(p_name text, p_flag text default null, p_is_active boolean default true, p_president_available boolean default false)
returns uuid
language plpgsql security definer
set search_path = public
as $$
declare v_id uuid;
begin
  if not public.is_world_admin() then raise exception 'Apenas o Super Admin pode cadastrar países.'; end if;
  if length(trim(coalesce(p_name,''))) < 2 then raise exception 'Informe o nome do país.'; end if;
  insert into public.countries(name,flag,is_active,president_available)
    values(trim(p_name),nullif(trim(p_flag),''),p_is_active,p_president_available)
    on conflict(name) do update set flag=excluded.flag,is_active=excluded.is_active,president_available=excluded.president_available
    returning id into v_id;
  return v_id;
end;
$$;

